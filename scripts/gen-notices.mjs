// Generates THIRD_PARTY.md from the production dependency closure.
// Usage: node scripts/gen-notices.mjs > THIRD_PARTY.md (then review the diff).
import { execFileSync } from "node:child_process";
import { readFileSync } from "node:fs";

const args = ["-r", "list", "--prod", "--depth", "Infinity", "--json"];
const rawBuffer =
  process.platform === "win32"
    ? execFileSync("cmd.exe", ["/d", "/s", "/c", `pnpm ${args.join(" ")}`], {
        maxBuffer: 16 * 1024 * 1024,
      })
    : execFileSync("pnpm", args, { maxBuffer: 16 * 1024 * 1024 });
// pnpm on Windows emits UTF-16; normalize before parsing.
const raw =
  rawBuffer[0] === 0xff && rawBuffer[1] === 0xfe
    ? rawBuffer.toString("utf16le")
    : rawBuffer.toString("utf8");
const snapshot = JSON.parse(raw);
const seen = new Map();

function licenseOf(name, dir) {
  try {
    const pkg = JSON.parse(readFileSync(`${dir}/package.json`, "utf8"));
    const lic = pkg.license ?? pkg.licenses;
    if (typeof lic === "string") return lic;
    if (lic) return JSON.stringify(lic);
    return "UNKNOWN (no license field)";
  } catch {
    return "UNKNOWN (not installed on this platform — review before release)";
  }
}

function walk(deps, paths) {
  for (const [name, info] of Object.entries(deps ?? {})) {
    const key = `${name}@${info.version}`;
    if (seen.has(key)) continue;
    seen.set(key, {
      name,
      version: info.version,
      license: licenseOf(name, info.path),
      path: info.path,
    });
    walk(info.dependencies, paths);
  }
}

for (const project of snapshot) walk(project.dependencies);

const rows = [...seen.values()]
  .filter((row) => !row.name.startsWith("@browser-bridge/"))
  .sort((a, b) => a.name.localeCompare(b.name));
console.log(`# Third-party notices

Production dependency closure for Browser Bridge packages, generated by
\`node scripts/gen-notices.mjs\`. Review license changes before release.
Total packages: ${rows.length}
`);
for (const row of rows) {
  console.log(`- ${row.name} ${row.version} — ${row.license}`);
}
